//! Domain entities and transaction state primitives for agent-2pc.

use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::fmt;
use std::path::PathBuf;
use thiserror::Error;
use uuid::Uuid;

/// Unique identifier for an agent transaction.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct TransactionId(pub Uuid);

impl TransactionId {
    /// Generate a new random transaction ID.
    pub fn new() -> Self {
        Self(Uuid::new_v4())
    }

    /// Parse transaction ID from string.
    pub fn parse(s: &str) -> Result<Self, TxError> {
        Uuid::parse_str(s)
            .map(Self)
            .map_err(|e| TxError::InvalidTransactionId(e.to_string()))
    }
}

impl Default for TransactionId {
    fn default() -> Self {
        Self::new()
    }
}

impl fmt::Display for TransactionId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.0)
    }
}

/// Identifier for a participating resource manager in a transaction.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub struct ParticipantId(pub String);

impl ParticipantId {
    pub fn new(id: impl Into<String>) -> Self {
        Self(id.into())
    }
}

impl fmt::Display for ParticipantId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}", self.0)
    }
}

/// Lifecycle states of a Two-Phase Commit transaction.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum TxState {
    /// Transaction has begun, participants are staging work.
    Active,
    /// Coordinator has issued PREPARE to all participants.
    Preparing,
    /// All participants voted PREPARED; ready for global commit decision.
    Prepared,
    /// Coordinator decided COMMIT; participants are executing commit.
    Committing,
    /// All participants committed successfully. Final terminal state.
    Committed,
    /// Coordinator or participant triggered abort; compensating actions running.
    Aborting,
    /// Transaction rolled back cleanly. Final terminal state.
    Aborted,
}

impl fmt::Display for TxState {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            TxState::Active => write!(f, "ACTIVE"),
            TxState::Preparing => write!(f, "PREPARING"),
            TxState::Prepared => write!(f, "PREPARED"),
            TxState::Committing => write!(f, "COMMITTING"),
            TxState::Committed => write!(f, "COMMITTED"),
            TxState::Aborting => write!(f, "ABORTING"),
            TxState::Aborted => write!(f, "ABORTED"),
        }
    }
}

/// Vote cast by a participant during Phase 1 (PREPARE).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub enum ParticipantVote {
    /// Participant has successfully isolated changes and guarantees commit readiness.
    Prepared(StageReceipt),
    /// Participant cannot guarantee atomic execution or invariant failed.
    Aborted { reason: String },
}

/// Receipt generated by a resource manager during Phase 1.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct StageReceipt {
    pub participant_id: ParticipantId,
    pub stage_path: Option<PathBuf>,
    pub backup_paths: Vec<PathBuf>,
    pub idempotency_key: Option<String>,
    pub metadata: HashMap<String, String>,
    pub timestamp: DateTime<Utc>,
}

impl StageReceipt {
    pub fn new(participant_id: ParticipantId) -> Self {
        Self {
            participant_id,
            stage_path: None,
            backup_paths: Vec::new(),
            idempotency_key: None,
            metadata: HashMap::new(),
            timestamp: Utc::now(),
        }
    }
}

/// Concrete intents that an AI agent stages across heterogeneous adapters.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "type", rename_all = "snake_case")]
pub enum ResourceIntent {
    /// Atomic filesystem write: writes content to file path with backup & staging.
    FsWrite {
        path: PathBuf,
        content: String,
        create_dirs: bool,
    },
    /// Atomic patch execution: applies unified diff to destination.
    FsPatch {
        path: PathBuf,
        patch: String,
    },
    /// Detached Git worktree transaction.
    GitBranch {
        repo_path: PathBuf,
        branch_name: String,
        commit_message: String,
    },
    /// Sandboxed command execution with staged outputs.
    Command {
        command: String,
        working_dir: PathBuf,
        env: HashMap<String, String>,
    },
    /// Hardened Linux unprivileged user-namespace sandboxed execution.
    SandboxCommand {
        command: String,
        working_dir: PathBuf,
        writable_paths: Vec<PathBuf>,
        env: HashMap<String, String>,
    },
    /// Governed execution with sliding-window velocity tripwires (fork-bomb, runaway loop defense).
    GovernedCommand {
        command: String,
        working_dir: PathBuf,
        max_forks: usize,
        timeout_ms: u64,
        env: HashMap<String, String>,
    },
    /// Hardware-isolated MicroVM ephemeral container execution.
    MicrovmCommand {
        command: String,
        working_dir: PathBuf,
        vcpus: u8,
        memory_mb: u32,
        env: HashMap<String, String>,
    },
    /// External REST API call with idempotency lease & compensation endpoint.
    RestApi {
        endpoint: String,
        method: String,
        headers: HashMap<String, String>,
        body: Option<String>,
        idempotency_key: String,
        compensation_endpoint: Option<String>,
        compensation_method: Option<String>,
        compensation_body: Option<String>,
    },
}

/// Errors raised across the Two-Phase Commit coordinator.
#[derive(Debug, Error)]
pub enum TxError {
    #[error("Invalid transaction ID: {0}")]
    InvalidTransactionId(String),

    #[error("Transaction not found: {0}")]
    TransactionNotFound(TransactionId),

    #[error("Transaction {0} is in invalid state {1} for operation {2}")]
    InvalidState(TransactionId, TxState, &'static str),

    #[error("Participant {0} failed to prepare: {1}")]
    PrepareFailed(ParticipantId, String),

    #[error("Participant {0} failed to commit: {1}")]
    CommitFailed(ParticipantId, String),

    #[error("Participant {0} failed to abort / compensate: {1}")]
    AbortFailed(ParticipantId, String),

    #[error("Transaction {0} timed out after {1} ms")]
    TransactionTimeout(TransactionId, u64),

    #[error("WAL error: {0}")]
    WalError(String),

    #[error("Checksum mismatch in WAL record: expected 0x{expected:08x}, got 0x{found:08x}")]
    ChecksumMismatch { expected: u32, found: u32 },

    #[error("IO error: {0}")]
    Io(#[from] std::io::Error),

    #[error("Serialization error: {0}")]
    Serialization(#[from] serde_json::Error),

    #[error("General coordinator error: {0}")]
    Other(String),
}
